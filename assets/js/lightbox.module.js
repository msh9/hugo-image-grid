// Read an album entry from a lightbox link's attributes. Every metadata field is optional.
function albumEntryFromLink(link) {
  // NB: Regarding link, we need the full URL as would be generated by the browser client and not the
  // literal href attribute value.
  const fallback = link.getAttribute('data-lb-href-fallback');
  const width = parseInt(link.getAttribute('data-lb-width'), 10);
  const height = parseInt(link.getAttribute('data-lb-height'), 10);
  const hasDimensions = width > 0 && height > 0;
  return {
    alt: link.getAttribute('data-lb-alt') ?? link.querySelector('img')?.getAttribute('alt') ?? '',
    caption: link.getAttribute('data-lb-caption') ?? undefined,
    copyright: link.getAttribute('data-lb-copyright') ?? undefined,
    fallback: fallback ? new URL(fallback, document.baseURI).href : undefined,
    height: hasDimensions ? height : undefined,
    link: link.href,
    title: link.getAttribute('data-lb-title') ?? undefined,
    typeHint: link.getAttribute('data-lb-typehint-fallback') || undefined,
    width: hasDimensions ? width : undefined
  };
}

// Collect every link that shares the clicked link's data-lightbox value, in document order.
// Returns the album along with the clicked link's position in it.
function buildAlbum(link) {
  const group = link.getAttribute('data-lightbox');
  // Only quotes and backslashes need escaping inside a quoted attribute selector.
  const links = group
    ? [...document.querySelectorAll('a[data-lightbox="' + group.replace(/["\\]/g, '\\$&') + '"]')]
    : [link];

  return {
    album: links.map(albumEntryFromLink),
    index: Math.max(links.indexOf(link), 0)
  };
}

